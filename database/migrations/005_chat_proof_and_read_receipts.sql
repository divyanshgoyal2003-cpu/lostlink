-- Sprint 12: private in-chat proof requests, per-user read cursors, and
-- idempotent message submission. Existing messages and claim history remain.

BEGIN;

ALTER TABLE messages
    ADD COLUMN client_message_id UUID;

CREATE UNIQUE INDEX uq_messages_client_message_id
    ON messages (conversation_id, sender_user_id, client_message_id)
    WHERE client_message_id IS NOT NULL;

ALTER TABLE messages
    ADD CONSTRAINT uq_messages_message_conversation
    UNIQUE (message_id, conversation_id);

CREATE TABLE conversation_read_states (
    conversation_id BIGINT NOT NULL
        REFERENCES conversations(conversation_id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL
        REFERENCES users(user_id) ON DELETE RESTRICT,
    last_read_message_id BIGINT,
    read_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT conversation_read_states_pkey
        PRIMARY KEY (conversation_id, user_id),
    CONSTRAINT fk_conversation_read_states_message
        FOREIGN KEY (last_read_message_id, conversation_id)
        REFERENCES messages(message_id, conversation_id)
        ON DELETE SET NULL (last_read_message_id)
);

CREATE INDEX idx_conversation_read_states_user
    ON conversation_read_states (user_id, read_at DESC);

CREATE TABLE conversation_proof_requests (
    proof_request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL
        REFERENCES conversations(conversation_id) ON DELETE RESTRICT,
    requester_user_id BIGINT NOT NULL
        REFERENCES users(user_id) ON DELETE RESTRICT,
    recipient_user_id BIGINT NOT NULL
        REFERENCES users(user_id) ON DELETE RESTRICT,
    proof_category VARCHAR(40) NOT NULL
        CHECK (proof_category IN (
            'PURCHASE_RECEIPT',
            'PRE_LOSS_PHOTO',
            'DISTINGUISHING_MARK',
            'PACKAGING_LABEL_SERIAL',
            'OTHER'
        )),
    request_text TEXT NOT NULL
        CHECK (length(trim(request_text)) BETWEEN 1 AND 500),
    request_status VARCHAR(30) NOT NULL DEFAULT 'OPEN'
        CHECK (request_status IN (
            'OPEN',
            'SUBMITTED',
            'NEEDS_MORE_INFORMATION',
            'ACCEPTED',
            'CANCELLED'
        )),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_conversation_proof_distinct_participants
        CHECK (requester_user_id <> recipient_user_id),
    CONSTRAINT uq_conversation_proof_request_conversation
        UNIQUE (proof_request_id, conversation_id)
);

CREATE INDEX idx_conversation_proof_requests_timeline
    ON conversation_proof_requests (conversation_id, created_at, proof_request_id);

CREATE INDEX idx_conversation_proof_requests_recipient_status
    ON conversation_proof_requests (recipient_user_id, request_status, created_at DESC);

CREATE TABLE conversation_proof_attachments (
    proof_attachment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proof_request_id BIGINT NOT NULL,
    conversation_id BIGINT NOT NULL,
    uploaded_by_user_id BIGINT NOT NULL
        REFERENCES users(user_id) ON DELETE RESTRICT,
    storage_key UUID NOT NULL UNIQUE,
    content_type VARCHAR(100) NOT NULL
        CHECK (content_type IN ('application/pdf', 'image/jpeg', 'image/png', 'image/webp')),
    byte_size BIGINT NOT NULL CHECK (byte_size > 0),
    submission_note TEXT
        CHECK (submission_note IS NULL OR length(submission_note) <= 500),
    uploaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_conversation_proof_attachment_request
        FOREIGN KEY (proof_request_id, conversation_id)
        REFERENCES conversation_proof_requests(proof_request_id, conversation_id)
        ON DELETE RESTRICT,
    CONSTRAINT uq_conversation_proof_attachment_identity
        UNIQUE (proof_attachment_id, proof_request_id)
);

CREATE INDEX idx_conversation_proof_attachments_request_time
    ON conversation_proof_attachments (proof_request_id, uploaded_at, proof_attachment_id);

COMMIT;
