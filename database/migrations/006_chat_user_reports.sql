-- Chat abuse reports and moderation decisions.
-- Counts are enforced in the application under a lock on the reported user.
-- Existing chat messages and accounts are preserved.

BEGIN;

CREATE TABLE chat_user_reports (
    chat_user_report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    reported_user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    conversation_id BIGINT NOT NULL REFERENCES conversations(conversation_id) ON DELETE RESTRICT,
    message_id BIGINT NOT NULL,
    report_category VARCHAR(40) NOT NULL
        CHECK (report_category IN ('ABUSIVE_LANGUAGE', 'RUDE_OR_HARASSING')),
    report_details VARCHAR(500),
    report_status VARCHAR(20) NOT NULL DEFAULT 'OPEN'
        CHECK (report_status IN ('OPEN', 'DISMISSED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    reviewed_by_user_id BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
    reviewed_at TIMESTAMPTZ,
    CONSTRAINT chk_chat_user_report_not_self
        CHECK (reporter_user_id <> reported_user_id),
    CONSTRAINT chk_chat_user_report_review_state
        CHECK ((report_status = 'OPEN' AND reviewed_at IS NULL)
            OR (report_status = 'DISMISSED' AND reviewed_at IS NOT NULL)),
    CONSTRAINT fk_chat_user_report_message_conversation
        FOREIGN KEY (message_id, conversation_id)
        REFERENCES messages(message_id, conversation_id) ON DELETE RESTRICT,
    CONSTRAINT uq_chat_user_reporter_message
        UNIQUE (reporter_user_id, reported_user_id, message_id)
);

CREATE INDEX idx_chat_user_reports_target_open
    ON chat_user_reports (reported_user_id, created_at)
    WHERE report_status = 'OPEN';

CREATE INDEX idx_chat_user_reports_conversation
    ON chat_user_reports (conversation_id, created_at);

COMMIT;
