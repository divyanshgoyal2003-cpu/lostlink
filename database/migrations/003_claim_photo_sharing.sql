BEGIN;

CREATE TABLE IF NOT EXISTS claim_photo_shares (
    photo_share_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id BIGINT NOT NULL REFERENCES claim_requests(claim_id) ON DELETE CASCADE,
    granted_by_user_id BIGINT NOT NULL REFERENCES users(user_id),
    granted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    revoked_at TIMESTAMPTZ,
    revoked_by_user_id BIGINT REFERENCES users(user_id),
    CHECK (
        (revoked_at IS NULL AND revoked_by_user_id IS NULL)
        OR (revoked_at IS NOT NULL AND revoked_by_user_id IS NOT NULL)
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_claim_photo_shares_active
    ON claim_photo_shares (claim_id)
    WHERE revoked_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_claim_photo_shares_claim_history
    ON claim_photo_shares (claim_id, granted_at DESC);

COMMIT;
