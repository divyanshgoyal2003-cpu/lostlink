-- Sprint 11: authority destinations, membership history, report routing,
-- and separate finder-to-authority custody transfers.
-- Additive only. Existing reports default to DIRECT; claim/handover history
-- and existing tables are preserved.

BEGIN;

CREATE TABLE authority_destinations (
    authority_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destination_type VARCHAR(20) NOT NULL
        CHECK (destination_type IN ('INSTITUTION', 'CENTRAL')),
    name VARCHAR(200) NOT NULL CHECK (length(trim(name)) > 0),
    institution_type VARCHAR(80),
    official_email VARCHAR(254),
    contact_information VARCHAR(500),
    location_description VARCHAR(300),
    verification_status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (verification_status IN ('PENDING', 'VERIFIED', 'REJECTED')),
    destination_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK (destination_status IN ('ACTIVE', 'SUSPENDED', 'INACTIVE')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (destination_type <> 'CENTRAL' OR institution_type IS NULL)
);

CREATE UNIQUE INDEX uq_authority_destinations_single_central
    ON authority_destinations (destination_type)
    WHERE destination_type = 'CENTRAL';
CREATE UNIQUE INDEX uq_authority_destinations_institution_identity
    ON authority_destinations (lower(name), lower(COALESCE(location_description, '')))
    WHERE destination_type = 'INSTITUTION';
CREATE INDEX idx_authority_destinations_eligibility
    ON authority_destinations (verification_status, destination_status, destination_type);

-- The central destination is a stable destination type; it does not grant
-- permissions to staff. Every staff action still checks current DB role and
-- current destination membership in application authorization.
INSERT INTO authority_destinations (
    destination_type, name, verification_status, destination_status
)
VALUES ('CENTRAL', 'LostLink Central Authority', 'VERIFIED', 'ACTIVE')
ON CONFLICT (destination_type) WHERE destination_type = 'CENTRAL' DO NOTHING;

CREATE TABLE authority_memberships (
    membership_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    authority_id BIGINT NOT NULL
        REFERENCES authority_destinations(authority_id) ON DELETE RESTRICT,
    -- RESTRICT keeps membership/security history when a user is deleted.
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    membership_role VARCHAR(30) NOT NULL DEFAULT 'MEMBER'
        CHECK (membership_role IN ('MEMBER', 'REVIEWER', 'MANAGER')),
    membership_status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (membership_status IN ('PENDING', 'ACTIVE', 'REJECTED', 'REVOKED', 'SUSPENDED')),
    requested_by_user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    reviewed_by_user_id BIGINT REFERENCES users(user_id) ON DELETE RESTRICT,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    reviewed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (reviewed_by_user_id IS NULL OR reviewed_by_user_id <> user_id),
    CHECK ((reviewed_by_user_id IS NULL) = (reviewed_at IS NULL)),
    -- Composite key permits custody receipt to reference a membership only
    -- together with the authority that membership belongs to.
    UNIQUE (membership_id, authority_id)
);

CREATE UNIQUE INDEX uq_authority_memberships_pending_or_active
    ON authority_memberships (authority_id, user_id)
    WHERE membership_status IN ('PENDING', 'ACTIVE');
CREATE INDEX idx_authority_memberships_user_status
    ON authority_memberships (user_id, membership_status, authority_id);
CREATE INDEX idx_authority_memberships_authority_status
    ON authority_memberships (authority_id, membership_status, membership_role);

-- Each membership row is one application/history episode. Status changes and
-- their actor/admin authorization are recorded in audit_logs by the app;
-- membership rows are retained (never hard-deleted by this schema).

ALTER TABLE reports
    ADD COLUMN recovery_mode VARCHAR(20) NOT NULL DEFAULT 'DIRECT'
        CHECK (recovery_mode IN ('DIRECT', 'AUTHORITY')),
    ADD COLUMN authority_id BIGINT
        REFERENCES authority_destinations(authority_id) ON DELETE RESTRICT;

ALTER TABLE reports
    ADD CONSTRAINT chk_reports_recovery_assignment
    CHECK (
        (report_type = 'FOUND' AND (
            (recovery_mode = 'DIRECT' AND authority_id IS NULL)
            OR (recovery_mode = 'AUTHORITY' AND authority_id IS NOT NULL)
        ))
        OR (report_type = 'LOST' AND recovery_mode = 'DIRECT' AND authority_id IS NULL)
    );

-- Composite key ensures a custody transfer's authority is exactly the
-- authority assigned to its report. Report trigger below enforces FOUND.
CREATE UNIQUE INDEX uq_reports_id_authority
    ON reports (report_id, authority_id);
CREATE INDEX idx_reports_authority_assignment
    ON reports (authority_id, recovery_mode, status)
    WHERE authority_id IS NOT NULL;

CREATE FUNCTION lostlink_validate_report_authority_assignment()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.recovery_mode = 'AUTHORITY' THEN
        IF NEW.report_type <> 'FOUND' OR NEW.authority_id IS NULL THEN
            RAISE EXCEPTION 'Only found reports may be assigned to an authority'
                USING ERRCODE = '23514';
        END IF;
        PERFORM 1 FROM authority_destinations
         WHERE authority_id = NEW.authority_id
           AND verification_status = 'VERIFIED'
           AND destination_status = 'ACTIVE'
         FOR SHARE;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Authority destination must be verified and active'
                USING ERRCODE = '23514';
        END IF;
    ELSIF NEW.authority_id IS NOT NULL THEN
        RAISE EXCEPTION 'Direct recovery reports cannot have an authority assignment'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_reports_authority_assignment
BEFORE INSERT OR UPDATE OF report_type, recovery_mode, authority_id ON reports
FOR EACH ROW EXECUTE FUNCTION lostlink_validate_report_authority_assignment();

CREATE TABLE custody_transfer_requests (
    custody_transfer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT NOT NULL,
    authority_id BIGINT NOT NULL REFERENCES authority_destinations(authority_id) ON DELETE RESTRICT,
    initiated_by_user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    custody_status VARCHAR(24) NOT NULL DEFAULT 'PENDING_RECEIPT'
        CHECK (custody_status IN ('PENDING_RECEIPT', 'RECEIVED', 'CANCELLED', 'EXPIRED')),
    -- Application must store lower-case hex HMAC-SHA-256 only; the key must
    -- be external to the database and never logged or returned.
    code_hash VARCHAR(64) NOT NULL CHECK (code_hash ~ '^[a-f0-9]{64}$'),
    code_expires_at TIMESTAMPTZ NOT NULL,
    failed_attempt_count SMALLINT NOT NULL DEFAULT 0
        CHECK (failed_attempt_count BETWEEN 0 AND 5),
    received_by_membership_id BIGINT,
    initiated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    received_at TIMESTAMPTZ,
    cancelled_at TIMESTAMPTZ,
    expired_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    FOREIGN KEY (report_id, authority_id)
        REFERENCES reports(report_id, authority_id) ON DELETE RESTRICT,
    FOREIGN KEY (received_by_membership_id, authority_id)
        REFERENCES authority_memberships(membership_id, authority_id) ON DELETE RESTRICT,
    CHECK (code_expires_at > initiated_at),
    -- A newly inserted row must begin in PENDING_RECEIPT; the trigger below
    -- enforces this insert-only rule and all subsequent state transitions.
    CHECK (
        (custody_status = 'RECEIVED'
            AND received_at IS NOT NULL AND received_by_membership_id IS NOT NULL)
        OR (custody_status <> 'RECEIVED'
            AND received_at IS NULL AND received_by_membership_id IS NULL)
    ),
    CHECK ((custody_status = 'CANCELLED') = (cancelled_at IS NOT NULL)),
    CHECK ((custody_status = 'EXPIRED') = (expired_at IS NOT NULL))
);

CREATE UNIQUE INDEX uq_custody_transfer_one_pending_per_report
    ON custody_transfer_requests (report_id)
    WHERE custody_status = 'PENDING_RECEIPT';
CREATE INDEX idx_custody_transfer_authority_queue
    ON custody_transfer_requests (authority_id, custody_status, initiated_at DESC);
CREATE INDEX idx_custody_transfer_report_history
    ON custody_transfer_requests (report_id, initiated_at DESC);

CREATE FUNCTION lostlink_validate_custody_transfer()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    report_owner BIGINT;
    report_kind VARCHAR(10);
    report_mode VARCHAR(20);
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.custody_status <> 'PENDING_RECEIPT'
           OR NEW.received_by_membership_id IS NOT NULL
           OR NEW.received_at IS NOT NULL
           OR NEW.cancelled_at IS NOT NULL
           OR NEW.expired_at IS NOT NULL
           OR NEW.failed_attempt_count <> 0 THEN
            RAISE EXCEPTION 'Custody transfers must be created as a clean PENDING_RECEIPT request'
                USING ERRCODE = '23514';
        END IF;
        SELECT user_id, report_type, recovery_mode
          INTO report_owner, report_kind, report_mode
          FROM reports
         WHERE report_id = NEW.report_id AND authority_id = NEW.authority_id
         FOR UPDATE;
        IF NOT FOUND OR report_kind <> 'FOUND' OR report_mode <> 'AUTHORITY'
           OR report_owner <> NEW.initiated_by_user_id THEN
            RAISE EXCEPTION 'Custody must be initiated by the owner of the assigned found report'
                USING ERRCODE = '23514';
        END IF;
        PERFORM 1 FROM authority_destinations
         WHERE authority_id = NEW.authority_id
           AND verification_status = 'VERIFIED'
           AND destination_status = 'ACTIVE'
         FOR SHARE;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Assigned authority must be verified and active'
                USING ERRCODE = '23514';
        END IF;
    ELSE
        IF NEW.report_id IS DISTINCT FROM OLD.report_id
           OR NEW.authority_id IS DISTINCT FROM OLD.authority_id
           OR NEW.initiated_by_user_id IS DISTINCT FROM OLD.initiated_by_user_id
           OR NEW.code_hash IS DISTINCT FROM OLD.code_hash
           OR NEW.code_expires_at IS DISTINCT FROM OLD.code_expires_at
           OR NEW.initiated_at IS DISTINCT FROM OLD.initiated_at THEN
            RAISE EXCEPTION 'Custody transfer identity and issued code are immutable'
                USING ERRCODE = '23514';
        END IF;

        IF NEW.failed_attempt_count < OLD.failed_attempt_count
           OR NEW.failed_attempt_count > OLD.failed_attempt_count + 1 THEN
            RAISE EXCEPTION 'Custody code attempts must increase atomically by at most one'
                USING ERRCODE = '23514';
        END IF;

        IF OLD.custody_status <> 'PENDING_RECEIPT'
           AND NEW.custody_status <> OLD.custody_status THEN
            RAISE EXCEPTION 'Terminal custody transfers cannot be reopened or changed'
                USING ERRCODE = '23514';
        END IF;
        IF OLD.custody_status <> 'PENDING_RECEIPT'
           AND (NEW.failed_attempt_count IS DISTINCT FROM OLD.failed_attempt_count
             OR NEW.received_by_membership_id IS DISTINCT FROM OLD.received_by_membership_id
             OR NEW.received_at IS DISTINCT FROM OLD.received_at
             OR NEW.cancelled_at IS DISTINCT FROM OLD.cancelled_at
             OR NEW.expired_at IS DISTINCT FROM OLD.expired_at) THEN
            RAISE EXCEPTION 'Terminal custody transfer history is immutable'
                USING ERRCODE = '23514';
        END IF;

        IF OLD.custody_status = 'PENDING_RECEIPT'
           AND NEW.custody_status NOT IN ('PENDING_RECEIPT', 'RECEIVED', 'CANCELLED', 'EXPIRED') THEN
            RAISE EXCEPTION 'Invalid custody transfer state transition'
                USING ERRCODE = '23514';
        END IF;
    END IF;

    IF TG_OP = 'UPDATE' AND NEW.custody_status = 'RECEIVED'
       AND OLD.custody_status <> 'RECEIVED' THEN
        IF NEW.code_expires_at <= clock_timestamp() OR NEW.failed_attempt_count >= 5 THEN
            RAISE EXCEPTION 'Expired or locked custody code cannot confirm receipt'
                USING ERRCODE = '23514';
        END IF;
        PERFORM 1 FROM authority_destinations
         WHERE authority_id = NEW.authority_id
           AND verification_status = 'VERIFIED'
           AND destination_status = 'ACTIVE'
         FOR SHARE;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Suspended or unverified authority cannot confirm receipt'
                USING ERRCODE = '23514';
        END IF;
        PERFORM 1 FROM authority_memberships
         WHERE membership_id = NEW.received_by_membership_id
           AND authority_id = NEW.authority_id
           AND membership_status = 'ACTIVE'
         FOR SHARE;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Receiving authority membership must be active'
                USING ERRCODE = '23514';
        END IF;
    ELSIF TG_OP = 'UPDATE' AND NEW.custody_status = 'EXPIRED'
       AND OLD.custody_status = 'PENDING_RECEIPT'
       AND NEW.code_expires_at > clock_timestamp() THEN
        RAISE EXCEPTION 'A custody request cannot expire before its code expires'
            USING ERRCODE = '23514';
    ELSIF TG_OP = 'UPDATE' AND OLD.custody_status <> 'PENDING_RECEIPT'
       AND NEW.custody_status <> OLD.custody_status THEN
        RAISE EXCEPTION 'Only pending custody transfers may change state'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_custody_transfer_validate
BEFORE INSERT OR UPDATE ON custody_transfer_requests
FOR EACH ROW EXECUTE FUNCTION lostlink_validate_custody_transfer();

-- Transaction contract for initiation/replacement:
--   1. BEGIN and lock the found report row FOR UPDATE.
--   2. Call this function for that report. It locks the same report row and
--      expires any pending request whose code has expired.
--   3. If an unexpired pending request remains, reject replacement. Otherwise
--      insert the new PENDING_RECEIPT row and its audit_logs event before
--      COMMIT. The report lock serializes concurrent attempts; the partial
--      unique index is the final guard. Expiration and replacement audit
--      events must commit or roll back with the state change/request.
-- Receipt/cancel operations must use the same report-then-transfer row-lock
-- order, perform their security checks and write audit_logs in one transaction.
-- This table is separate from claimant handover_records and claimant codes.
CREATE FUNCTION lostlink_expire_pending_custody(p_report_id BIGINT)
RETURNS INTEGER LANGUAGE plpgsql AS $$
DECLARE
    changed_count INTEGER;
    report_found BOOLEAN;
BEGIN
    PERFORM 1 FROM reports WHERE report_id = p_report_id FOR UPDATE;
    report_found := FOUND;
    IF NOT report_found THEN
        RAISE EXCEPTION 'Report does not exist'
            USING ERRCODE = '23503';
    END IF;
    UPDATE custody_transfer_requests
       SET custody_status = 'EXPIRED', expired_at = clock_timestamp(), updated_at = clock_timestamp()
     WHERE report_id = p_report_id
       AND custody_status = 'PENDING_RECEIPT'
       AND code_expires_at <= clock_timestamp();
    GET DIAGNOSTICS changed_count = ROW_COUNT;
    RETURN changed_count;
END;
$$;

COMMIT;
