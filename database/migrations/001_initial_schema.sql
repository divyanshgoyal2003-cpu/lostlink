-- LostLink initial schema migration
-- PostgreSQL + PostGIS
-- Run while connected to the lostlink database.

BEGIN;

CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE IF NOT EXISTS users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    phone VARCHAR(30),
    password_hash TEXT NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'USER'
        CHECK (role IN ('USER', 'STAFF', 'ADMIN')),
    account_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK (account_status IN ('ACTIVE', 'SUSPENDED', 'DELETED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS items (
    item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category VARCHAR(30) NOT NULL
        CHECK (category IN ('ELECTRONICS', 'DOC_CARDS', 'ACCESSORIES', 'CLOTHING', 'BAGS', 'OTHER')),
    title VARCHAR(160) NOT NULL,
    description TEXT,
    color VARCHAR(60),
    attributes_json JSONB NOT NULL DEFAULT '{}'::jsonb
        CHECK (jsonb_typeof(attributes_json) = 'object'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS electronics (
    item_id BIGINT PRIMARY KEY REFERENCES items(item_id) ON DELETE CASCADE,
    brand VARCHAR(100),
    model VARCHAR(100),
    serial_number_private TEXT
);

CREATE TABLE IF NOT EXISTS doc_cards (
    item_id BIGINT PRIMARY KEY REFERENCES items(item_id) ON DELETE CASCADE,
    document_type VARCHAR(80),
    holder_name_private VARCHAR(160),
    identifier_private TEXT
);

CREATE TABLE IF NOT EXISTS accessories (
    item_id BIGINT PRIMARY KEY REFERENCES items(item_id) ON DELETE CASCADE,
    material VARCHAR(80),
    distinctive_marks TEXT
);

CREATE TABLE IF NOT EXISTS item_tags (
    item_id BIGINT NOT NULL REFERENCES items(item_id) ON DELETE CASCADE,
    tag_word VARCHAR(80) NOT NULL,
    PRIMARY KEY (item_id, tag_word)
);

CREATE TABLE IF NOT EXISTS reports (
    report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    item_id BIGINT NOT NULL UNIQUE REFERENCES items(item_id),
    report_type VARCHAR(10) NOT NULL CHECK (report_type IN ('LOST', 'FOUND')),
    report_time TIMESTAMPTZ NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'OPEN'
        CHECK (status IN ('OPEN', 'MATCHED', 'CLAIM_PENDING', 'RETURNED', 'CLOSED', 'CANCELLED')),
    location_point geography(Point, 4326) NOT NULL,
    uncertainty_radius_m DOUBLE PRECISION NOT NULL DEFAULT 75
        CHECK (uncertainty_radius_m >= 0 AND uncertainty_radius_m <= 5000),
    location_accuracy_m DOUBLE PRECISION
        CHECK (location_accuracy_m IS NULL OR location_accuracy_m >= 0),
    location_source VARCHAR(20) NOT NULL
        CHECK (location_source IN ('GPS', 'MAP_PIN')),
    location_description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS item_photos (
    photo_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL REFERENCES items(item_id) ON DELETE CASCADE,
    storage_key TEXT NOT NULL,
    photo_type VARCHAR(40),
    uploaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS match_records (
    match_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lost_report_id BIGINT NOT NULL REFERENCES reports(report_id),
    found_report_id BIGINT NOT NULL REFERENCES reports(report_id),
    location_score NUMERIC(5,2) NOT NULL CHECK (location_score BETWEEN 0 AND 100),
    item_score NUMERIC(5,2) NOT NULL CHECK (item_score BETWEEN 0 AND 100),
    time_score NUMERIC(5,2) NOT NULL CHECK (time_score BETWEEN 0 AND 100),
    description_score NUMERIC(5,2) NOT NULL CHECK (description_score BETWEEN 0 AND 100),
    total_score NUMERIC(5,2) NOT NULL CHECK (total_score BETWEEN 0 AND 100),
    score_breakdown JSONB NOT NULL DEFAULT '{}'::jsonb
        CHECK (jsonb_typeof(score_breakdown) = 'object'),
    match_status VARCHAR(30) NOT NULL DEFAULT 'CANDIDATE'
        CHECK (match_status IN ('CANDIDATE', 'CHAT_ENABLED', 'CLAIM_PENDING', 'VERIFIED', 'REJECTED', 'RETURNED')),
    calculated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_match_report_pair UNIQUE (lost_report_id, found_report_id),
    CONSTRAINT chk_match_reports_differ CHECK (lost_report_id <> found_report_id)
);

CREATE TABLE IF NOT EXISTS claim_requests (
    claim_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id BIGINT NOT NULL REFERENCES match_records(match_id),
    claimant_user_id BIGINT NOT NULL REFERENCES users(user_id),
    claim_status VARCHAR(30) NOT NULL DEFAULT 'SUBMITTED'
        CHECK (claim_status IN ('SUBMITTED', 'IN_REVIEW', 'APPROVED', 'REJECTED', 'WITHDRAWN', 'COMPLETED')),
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS claim_verifications (
    verification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id BIGINT NOT NULL REFERENCES claim_requests(claim_id) ON DELETE CASCADE,
    reviewer_user_id BIGINT REFERENCES users(user_id),
    verification_type VARCHAR(40) NOT NULL,
    verification_status VARCHAR(30) NOT NULL
        CHECK (verification_status IN ('PENDING', 'PASSED', 'FAILED', 'NEEDS_REVIEW')),
    evidence_reference TEXT,
    review_notes_private TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    reviewed_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS conversations (
    conversation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id BIGINT NOT NULL UNIQUE REFERENCES claim_requests(claim_id) ON DELETE CASCADE,
    conversation_status VARCHAR(20) NOT NULL DEFAULT 'OPEN'
        CHECK (conversation_status IN ('OPEN', 'CLOSED', 'REPORTED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS messages (
    message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES conversations(conversation_id) ON DELETE CASCADE,
    sender_user_id BIGINT NOT NULL REFERENCES users(user_id),
    message_body TEXT NOT NULL CHECK (length(trim(message_body)) > 0),
    sent_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    read_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS notifications (
    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    notification_type VARCHAR(40) NOT NULL,
    reference_type VARCHAR(40),
    reference_id BIGINT,
    read_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS handover_records (
    handover_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id BIGINT NOT NULL UNIQUE REFERENCES claim_requests(claim_id),
    verified_by_user_id BIGINT REFERENCES users(user_id),
    handover_status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (handover_status IN ('PENDING', 'CODE_ISSUED', 'COMPLETED', 'CANCELLED', 'EXPIRED')),
    code_hash TEXT,
    code_expires_at TIMESTAMPTZ,
    code_used_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (code_used_at IS NULL OR code_expires_at IS NULL OR code_used_at <= code_expires_at)
);

CREATE TABLE IF NOT EXISTS audit_logs (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT REFERENCES users(user_id),
    action_type VARCHAR(80) NOT NULL,
    entity_type VARCHAR(60) NOT NULL,
    entity_id BIGINT,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb
        CHECK (jsonb_typeof(metadata) = 'object'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Indexes: spatial lookup, common filtering, and message history.
CREATE INDEX IF NOT EXISTS idx_reports_location_gist ON reports USING GIST (location_point);
CREATE INDEX IF NOT EXISTS idx_reports_type_status_time ON reports (report_type, status, report_time);
CREATE INDEX IF NOT EXISTS idx_reports_user ON reports (user_id);
CREATE INDEX IF NOT EXISTS idx_item_photos_item ON item_photos (item_id);
CREATE INDEX IF NOT EXISTS idx_match_records_lost ON match_records (lost_report_id);
CREATE INDEX IF NOT EXISTS idx_match_records_found ON match_records (found_report_id);
CREATE INDEX IF NOT EXISTS idx_claim_requests_match ON claim_requests (match_id);
CREATE INDEX IF NOT EXISTS idx_claim_requests_user_status ON claim_requests (claimant_user_id, claim_status);
CREATE INDEX IF NOT EXISTS idx_verifications_claim ON claim_verifications (claim_id, created_at);
CREATE INDEX IF NOT EXISTS idx_messages_conversation_sent ON messages (conversation_id, sent_at);
CREATE INDEX IF NOT EXISTS idx_notifications_user_read ON notifications (user_id, read_at);
CREATE INDEX IF NOT EXISTS idx_audit_logs_entity ON audit_logs (entity_type, entity_id, created_at);

-- Ensure every match connects a LOST report to a FOUND report in the correct order.
CREATE OR REPLACE FUNCTION validate_match_report_types()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    lost_type VARCHAR(10);
    found_type VARCHAR(10);
BEGIN
    SELECT report_type INTO lost_type FROM reports WHERE report_id = NEW.lost_report_id;
    SELECT report_type INTO found_type FROM reports WHERE report_id = NEW.found_report_id;

    IF lost_type IS DISTINCT FROM 'LOST' OR found_type IS DISTINCT FROM 'FOUND' THEN
        RAISE EXCEPTION 'Match must connect a LOST report to a FOUND report';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validate_match_report_types ON match_records;
CREATE TRIGGER trg_validate_match_report_types
BEFORE INSERT OR UPDATE OF lost_report_id, found_report_id ON match_records
FOR EACH ROW EXECUTE FUNCTION validate_match_report_types();

-- Enforce subtype/category consistency for subtype insert/update.
CREATE OR REPLACE FUNCTION validate_item_subtype_category()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    actual_category VARCHAR(30);
    expected_category VARCHAR(30);
BEGIN
    expected_category := CASE TG_TABLE_NAME
        WHEN 'electronics' THEN 'ELECTRONICS'
        WHEN 'doc_cards' THEN 'DOC_CARDS'
        WHEN 'accessories' THEN 'ACCESSORIES'
        ELSE NULL
    END;

    SELECT category INTO actual_category FROM items WHERE item_id = NEW.item_id;
    IF actual_category IS DISTINCT FROM expected_category THEN
        RAISE EXCEPTION 'Subtype % requires ITEMS.category = %', TG_TABLE_NAME, expected_category;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_electronics_category ON electronics;
CREATE TRIGGER trg_electronics_category BEFORE INSERT OR UPDATE ON electronics
FOR EACH ROW EXECUTE FUNCTION validate_item_subtype_category();
DROP TRIGGER IF EXISTS trg_doc_cards_category ON doc_cards;
CREATE TRIGGER trg_doc_cards_category BEFORE INSERT OR UPDATE ON doc_cards
FOR EACH ROW EXECUTE FUNCTION validate_item_subtype_category();
DROP TRIGGER IF EXISTS trg_accessories_category ON accessories;
CREATE TRIGGER trg_accessories_category BEFORE INSERT OR UPDATE ON accessories
FOR EACH ROW EXECUTE FUNCTION validate_item_subtype_category();

COMMIT;
